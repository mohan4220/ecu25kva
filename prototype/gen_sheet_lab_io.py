#!/usr/bin/env python3
"""lab_io sheet: pluggable screw terminals in place of the Bosch 94-way.

Exports the production connector sheet's 40 nets, each on a 5.08 mm
Phoenix MSTBA terminal grouped by job, plus TRIP_LOOP (production open
item 5.2) and two power-ground positions (open item 5.1). Pin 08, the
rail sensor's dedicated return, is GND here as on the production sheet;
CAM_GND_44 and SHIELD_30 stay labels, grounded where production grounds
them (speed_inputs).

The Pin field on each terminal names the production connector pin per
position, so a harness built for the bench maps straight onto the OEM one.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
sys.path.insert(1, os.path.join(HERE, "..", "hw"))
import schlib  # noqa: E402
from schlib import Sheet  # noqa: E402
from gen_sheet_mcu_stm32 import part  # noqa: E402

OUT = os.path.join(HERE, "lab_io.kicad_sch")
FP = ("Connector_Phoenix_MSTB:PhoenixContact_MSTBA_2,5_{n}-G-5,08_"
      "1x{n:02d}_P5.08mm_Horizontal")
SENSORS_IN = ["BOOST_P_IN", "BOOST_T_IN", "COOLANT_T_IN", "EGR_POS_IN",
              "OIL_P_IN", "RAIL_P_IN"]

# ref -> nets by position; (job, production pin per position)
TERMINALS = {
    "J1001": ["VBAT_IN", "V_BAT_1R", "V_BAT_2R", "GND"],
    "J1002": ["GND", "GND"],
    "J1003": ["INJ_A_03", "INJ_B_05", "INJ_LS1_73", "INJ_LS2_29",
              "INJ_LS3_07"],
    "J1004": ["MU_RETURN", "EGR_HIGH_59", "EGR_LOW_81", "RLY_MAIN_OUT",
              "RLY_BUZZER_OUT"],
    "J1005": ["EXC_BOOST_11", "EXC_EGR_15", "EXC_OIL_39", "EXC_RAIL_32",
              "EXC_CAM_45"] + SENSORS_IN + ["SGND_34", "SGND_36", "GND"],
    "J1006": ["CRANK_HI_52", "CRANK_LO_74", "CAM_FREQ_46", "CAM_GND_44",
              "SHIELD_30", "GND"],
    "J1007": ["SW_COOLANT_C", "SW_DROOP_C", "IN_AUDIO_ABORT_H",
              "IN_OVERRIDE_SS_H", "IN_IGNITION_H", "TRIP_LOOP"],
    "J1008": ["CAN1_H", "CAN1_L", "GND", "CAN2_H", "CAN2_L", "GND"],
}
JOB = {
    "J1001": ("power", "21 logic feed, 04 injector feed, 06 EGR feed, GND"),
    "J1002": ("power ground", "none on the OEM diagram (open item 5.1)"),
    "J1003": ("injectors", "03, 05, 73, 29, 07"),
    "J1004": ("actuators", "88, 59, 81, 50, 69"),
    "J1005": ("sensors", "11, 15, 39, 32, 45, 41, 79, 33, 37, 80, 35, 34, "
                         "36, 08 (rail sensor return)"),
    "J1006": ("speed", "52, 74, 46, 44, 30, GND"),
    "J1007": ("switches", "43, 23, 20, 24, 71, trip loop (open item 5.2)"),
    "J1008": ("CAN", "55, 77, GND, 87, 86, GND"),
}
# The bridge header: odd pins the signals a simulator drives, even pins GND
BRIDGE = ["CRANK_HI_52", "CRANK_LO_74", "CAM_FREQ_46"] + SENSORS_IN + \
         ["IN_IGNITION_H"]


def build():
    schlib.verify_pins()
    sh = Sheet("Lab terminals and bridge header (prototype)", paper="A3",
               comments=["Generated by prototype/gen_sheet_lab_io.py",
                         "Replaces the Bosch 94-way connector on the bench "
                         "prototype only",
                         "Field Pin: the production connector pin per "
                         "terminal position"],
               ref_base=schlib.REF_BASE["connector"])
    seen = set()

    def labelled(sh, libid, ref, x, y, names, fp, fields):
        # first appearance of a net is its hierarchical label, repeats are
        # local labels of the same name (same net on one sheet)
        part(sh, libid, "J", x, y, ref, fp, {}, fields=fields, ref=ref)
        from symbols import stock_pins, stub_dir
        from schlib import pin_xy
        for num, net in names.items():
            lx, ly, a, _ = stock_pins(libid)[num]
            px, py = pin_xy(lx, ly, x, y, 0)
            dx, dy = stub_dir(a)
            ex, ey = px + dx * 5.08, py + dy * 5.08
            sh.wire(px, py, ex, ey)
            rot = 180 if dx < 0 else 0
            if net == "GND":
                sh.gnd(ex, ey)
            elif net in seen:
                sh.label(net, ex, ey, rot=rot)
            else:
                sh.hlabel(net, ex, ey, shape="passive", rot=rot)
                seen.add(net)

    x0, y = 80.0, 40.0
    for i, (ref, names) in enumerate(TERMINALS.items()):
        n = len(names)
        x = x0 + (i % 4) * 90.0
        yy = y + (i // 4) * 100.0
        job, pins = JOB[ref]
        labelled(sh, f"Connector:Screw_Terminal_01x{n:02d}", ref, x, yy,
                 {str(i): net for i, net in enumerate(names, 1)}, FP.format(n=n),
                 {"Job": job, "Pin": pins,
                  "MPN": f"Phoenix MSTBA 2,5/{n}-G-5,08 + MSTB 2,5/{n}-ST-5,08",
                  "Rating": "12 A per position (Phoenix MSTBA 2,5)"})
    hdr = {}
    for i, net in enumerate(BRIDGE):
        hdr[str(2 * i + 1)] = net
        hdr[str(2 * i + 2)] = "GND"
    labelled(sh, "Connector_Generic:Conn_02x10_Odd_Even", "J1009", 170.0, 250.0,
             hdr, "Connector_PinHeader_2.54mm:PinHeader_2x10_P2.54mm_Vertical",
             {"Job": "signal bridge: a simulator board plugs in here",
              "Pin": "odd pins signals, even pins GND"})
    return sh


if __name__ == "__main__":
    print(build().write(OUT, force=True))
