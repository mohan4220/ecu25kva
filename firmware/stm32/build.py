#!/usr/bin/env python3
"""Build the prototype's firmware for the STM32G474 with zig (the project's
C compiler, from .venv), and nothing else to install.

    .venv/bin/python firmware/stm32/build.py            # app, bootloader, model build
    .venv/bin/python firmware/stm32/build.py --check    # also the pin cross-check

Writes firmware/stm32/build/:
    boot.elf / boot.hex          the bootloader, 32 KiB at 0x08000000
    app.elf / app.bin            the application, for the service tool's `flash`
    app_signed.hex               app.bin plus the header the bootloader accepts
                                 (hardware range 0x0000-0xFFFF: a bench board's
                                 blank end-of-line record reads revision 0)
    app_model.*                  the same with ECU_MODEL (the Simulink code)
    app_standalone.elf / .hex    the application alone at 0x08000000, no
                                 bootloader: the first thing on a new board

Flash over SWD (J301) with any ST-LINK tool, e.g.
    STM32_Programmer_CLI -c port=SWD -w build/boot.hex -w build/app_signed.hex -v -rst
    openocd -f interface/stlink.cfg -f target/stm32g4x.cfg \\
        -c "program build/app_standalone.hex verify reset exit"
"""
import os
import re
import struct
import subprocess
import sys
import zlib

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, "..", ".."))
FW = os.path.join(ROOT, "firmware")
OUT = os.path.join(HERE, "build")


def zig():
    z = os.environ.get("ZIG")
    if z:
        return z
    for p in (os.path.join(ROOT, ".venv", "Lib", "site-packages", "ziglang", "zig.exe"),
              os.path.join(ROOT, ".venv", "lib")):
        if p.endswith(".exe") and os.path.exists(p):
            return p
    import glob
    hits = glob.glob(os.path.join(ROOT, ".venv", "lib", "python*", "site-packages", "ziglang", "zig"))
    if hits:
        return hits[0]
    sys.exit("zig not found: pip install ziglang into .venv, or set ZIG")


# compile with musl's headers (string.h, math.h); link freestanding, where
# zig's compiler-rt supplies memcpy, memset, logf, fmodf and the rest
TARGET_CC = ["-target", "thumb-linux-musleabihf"]
TARGET_LD = ["-target", "thumb-freestanding-eabihf"]
CPU = ["-mcpu=cortex_m4+vfp4d16sp", "-mfloat-abi=hard", "-mthumb"]
CFLAGS = ["-std=c99", "-Os", "-g", "-ffunction-sections", "-fdata-sections", "-fno-common",
          "-fno-unwind-tables", "-fno-asynchronous-unwind-tables",
          "-Wall", "-Wextra", "-Werror", "-Wno-unused-parameter", "-DSTM32G474xx"]
VENDOR = os.path.join(HERE, "vendor")
TUSB = os.path.join(VENDOR, "tinyusb")
INC = [HERE, FW + "/core", FW + "/boot", VENDOR + "/st", VENDOR + "/cmsis", TUSB]

CORE = [os.path.join(FW, "core", f) for f in sorted(os.listdir(os.path.join(FW, "core")))
        if f.endswith(".c")]
GEN_DIRS = sorted(os.path.join(FW, "gen", d) for d in os.listdir(os.path.join(FW, "gen"))
                  if os.path.isdir(os.path.join(FW, "gen", d)))
GEN = [os.path.join(d, f) for d in GEN_DIRS for f in sorted(os.listdir(d)) if f.endswith(".c")]
CHIP_COMMON = [os.path.join(HERE, f) for f in ("startup.c", "clock.c", "gpio.c", "flash.c", "can.c",
                                                "usb.c")]
CHIP_APP = [os.path.join(HERE, f) for f in ("app_main.c", "adc.c", "timebase.c", "inj_hw.c",
                                             "inj_logic.c")]
TUSB_SRC = [os.path.join(TUSB, p) for p in (
    "tusb.c", "common/tusb_fifo.c", "device/usbd.c", "device/usbd_control.c",
    "class/cdc/cdc_device.c", "portable/st/stm32_fsdev/dcd_stm32_fsdev.c")]
BOOT_SRC = [os.path.join(HERE, "boot_main.c"), os.path.join(FW, "boot", "boot.c")] + [
    os.path.join(FW, "core", f) for f in ("service.c", "nvm.c", "isotp.c", "link.c", "eol.c")]

# board.h's flash map (one source: parsed, not retyped)
BOARD = open(os.path.join(HERE, "board.h"), encoding="utf-8").read()


def hexdef(name):
    m = re.search(r"#define %s (0x[0-9A-Fa-f]+)u" % name, BOARD)
    if not m:
        sys.exit(f"board.h: {name} not found")
    return int(m.group(1), 16)


APP_BASE, APP_END = hexdef("APP_BASE"), hexdef("APP_END")
APP_VECTORS = APP_BASE + 0x200
BOOT_SIZE = APP_BASE - 0x08000000
RAM0, RAM_LEN = 0x20000020, 96 * 1024 - 32       # SRAM1 + SRAM2; SHARED_RAM is below


LD = """/* generated by firmware/stm32/build.py */
ENTRY(Reset_Handler)
MEMORY {{
  FLASH (rx)  : ORIGIN = 0x{org:08X}, LENGTH = 0x{length:X}
  RAM   (rwx) : ORIGIN = 0x{ram:08X}, LENGTH = 0x{ramlen:X}
}}
_estack = ORIGIN(RAM) + LENGTH(RAM);
SECTIONS {{
  .isr_vector : {{ KEEP(*(.isr_vector)) }} > FLASH
  .text : {{
    *(.text*) *(.rodata*)
    . = ALIGN(4);
  }} > FLASH

  _sidata = LOADADDR(.data);
  .data : {{
    _sdata = .;
    *(.ramfunc*) *(.data*)
    . = ALIGN(4);
    _edata = .;
  }} > RAM AT > FLASH
  .bss (NOLOAD) : {{
    _sbss = .;
    *(.bss*) *(COMMON)
    . = ALIGN(4);
    _ebss = .;
  }} > RAM
  _flash_end = LOADADDR(.data) + SIZEOF(.data);
  {boot_info}
  /DISCARD/ : {{ *(.ARM.attributes) *(.comment) *(.ARM.extab*) *(.ARM.exidx*) }}
}}
"""
BOOT_INFO_LD = """.boot_info 0x{a:08X} : {{ KEEP(*(.boot_info)) }} > FLASH"""


def run(cmd):
    r = subprocess.run(cmd, capture_output=True, text=True)
    if r.returncode:
        print(" ".join(os.path.basename(c) if os.path.isabs(c) else c for c in cmd[:3]), "...")
        sys.stdout.write(r.stdout + r.stderr)
        sys.exit(f"build failed: {os.path.basename(cmd[-1])}")
    return r.stdout


def compile_all(srcs, objdir, extra):
    z = zig()
    os.makedirs(objdir, exist_ok=True)
    objs = []
    for s in srcs:
        rel = os.path.relpath(s, ROOT).replace(os.sep, "_").replace("/", "_")
        o = os.path.join(objdir, rel[:-2] + ".o")
        flags = list(CFLAGS)
        if s.startswith(TUSB):                      # vendored: GNU C, and its warnings are not ours
            flags = ["-std=gnu99" if f == "-std=c99" else f for f in flags
                     if f not in ("-Werror", "-Wextra")]
        run([z, "cc", *TARGET_CC, *CPU, *flags, *extra, *[f"-I{i}" for i in INC], "-c", s, "-o", o])
        objs.append(o)
    return objs


def link(name, objs, org, length, boot_info=False):
    z = zig()
    ld = os.path.join(OUT, name + ".ld")
    bi = BOOT_INFO_LD.format(a=0x08007FE0) if boot_info else ""
    open(ld, "w").write(LD.format(org=org, length=length, ram=RAM0, ramlen=RAM_LEN, boot_info=bi))
    elf = os.path.join(OUT, name + ".elf")
    run([z, "cc", *TARGET_LD, *CPU, "-nostartfiles", "-T", ld, "-Wl,--gc-sections",
         "-o", elf, *objs])
    return elf


def objcopy(elf, fmt, out):
    if fmt == "ihex":                               # zig's objcopy writes binary; HEX is ours
        tmp = out + ".bin.tmp"
        run([zig(), "objcopy", "-O", "binary", elf, tmp])
        data = open(tmp, "rb").read()
        os.remove(tmp)
        base = symbols(elf)["vectors"][0]
        open(out, "w").write(ihex([(base, data)]))
        return out
    run([zig(), "objcopy", "-O", fmt, elf, out])
    return out


def symbols(elf):
    """name -> (address, size), read from the ELF32 symbol table"""
    d = open(elf, "rb").read()
    if d[:4] != b"\x7fELF" or d[4] != 1:
        sys.exit(f"{elf}: not ELF32")
    shoff, = struct.unpack_from("<I", d, 0x20)
    shentsize, shnum = struct.unpack_from("<HH", d, 0x2E)
    secs = [struct.unpack_from("<IIIIIIIIII", d, shoff + i * shentsize) for i in range(shnum)]
    out = {}
    for s in secs:
        if s[1] != 2:                                   # SHT_SYMTAB
            continue
        strtab = secs[s[6]]
        for i in range(s[5] // 16):
            name, value, size = struct.unpack_from("<III", d, s[4] + i * 16)
            n0 = strtab[4] + name
            out[d[n0:d.index(b"\0", n0)].decode()] = (value, size)
    return out


def ihex(chunks):
    """chunks: [(address, bytes)] -> Intel HEX text"""
    lines = []

    def rec(t, a, data):
        b = bytes([len(data), a >> 8 & 0xFF, a & 0xFF, t]) + data
        lines.append(":" + (b + bytes([-sum(b) & 0xFF])).hex().upper())
    for addr, data in chunks:
        upper = None
        for i in range(0, len(data), 16):
            a = addr + i
            if a >> 16 != upper:
                upper = a >> 16
                rec(4, 0, struct.pack(">H", upper))
            rec(0, a & 0xFFFF, data[i:i + 16])
    rec(1, 0, b"")
    return "\n".join(lines) + "\n"


def size_report(name, elf, limit_end):
    s = symbols(elf)
    end = s.get("_flash_end", (0, 0))[0]
    ram = s.get("_ebss", (0, 0))[0] - RAM0
    print(f"  {name:16} flash to 0x{end:08X}   RAM {ram / 1024:5.1f} KiB")
    if end > limit_end:
        sys.exit(f"{name}: flash ends at 0x{end:08X}, past 0x{limit_end:08X}")
    return end


def app(name, extra, signed=True):
    objdir = os.path.join(OUT, "obj_" + name)
    objs = compile_all(CORE + (GEN if "-DECU_MODEL" in extra else []) + CHIP_COMMON + CHIP_APP + TUSB_SRC,
                       objdir, extra + [f"-I{d}" for d in GEN_DIRS])
    elf = link(name, objs, APP_VECTORS, APP_END - APP_VECTORS)
    # code must stay in bank 1, so stored-data writes in bank 2 never stall it
    size_report(name, elf, 0x08040000)
    binf = objcopy(elf, "binary", os.path.join(OUT, name + ".bin"))
    # the service tool writes the image at APP_BASE + 64: pad to the vectors
    img = b"\xFF" * (APP_VECTORS - APP_BASE - 64) + open(binf, "rb").read()
    open(binf, "wb").write(img)
    if signed:
        hdr = struct.pack("<IIIIIHH", 0x1A6EC25, 1, len(img), zlib.crc32(img), 0x00010000, 0x0000, 0xFFFF)
        hdr += b"\xFF" * (64 - len(hdr))
        open(os.path.join(OUT, name + "_signed.hex"), "w").write(ihex([(APP_BASE, hdr + img)]))
    return elf


def standalone():
    objdir = os.path.join(OUT, "obj_app")          # same objects as `app`
    objs = [os.path.join(objdir, f) for f in sorted(os.listdir(objdir)) if f.endswith(".o")]
    elf = link("app_standalone", objs, 0x08000000, APP_END - 0x08000000)
    size_report("app_standalone", elf, 0x08040000)
    objcopy(elf, "ihex", os.path.join(OUT, "app_standalone.hex"))


def boot():
    objdir = os.path.join(OUT, "obj_boot")
    objs = compile_all(BOOT_SRC + CHIP_COMMON + TUSB_SRC, objdir, ["-DECU_BOOT"])
    elf = link("boot", objs, 0x08000000, BOOT_SIZE, boot_info=True)
    size_report("boot", elf, 0x08007FE0)
    objcopy(elf, "ihex", os.path.join(OUT, "boot.hex"))


def check_pins():
    """board.h's pins and AF numbers against prototype/stm32_pins.py and ST's GPIO data"""
    sys.path.insert(0, os.path.join(ROOT, "prototype"))
    import stm32_pins as sp
    import xml.etree.ElementTree as ET
    af = {}
    gp = ET.parse(os.path.join(ROOT, "prototype", "lib", "GPIO-STM32G47x_gpio_v1_0_Modes.xml")).getroot()
    for p in gp.iter():
        if p.tag.endswith("GPIO_Pin"):
            for sig in p:
                if sig.tag.endswith("PinSignal"):
                    for v in sig.iter():
                        if v.tag.endswith("PossibleValue") and v.text and v.text.startswith("GPIO_AF"):
                            af[(p.get("Name"), sig.get("Name"))] = int(re.match(r"GPIO_AF(\d+)", v.text).group(1))
    bad = []
    pins = {n: f"P{port}{num}" for n, port, num in
            re.findall(r"#define (P_\w+) PIN\('([A-G])', (\d+)\)", BOARD)}
    sig_of = {"P_INJ_LS1": "INJ_LS_1", "P_INJ_LS2": "INJ_LS_2", "P_INJ_LS3": "INJ_LS_3",
              "P_INJ_HS_A": "INJ_HS_A", "P_INJ_HS_B": "INJ_HS_B", "P_INJ_HS_A_BAT": "INJ_HS_A_BAT",
              "P_INJ_HS_B_BAT": "INJ_HS_B_BAT", "P_MU_PWM": "MU_PWM", "P_EGR_IN1": "EGR_IN1",
              "P_EGR_IN2": "EGR_IN2", "P_EGR_EN": "EGR_EN", "P_RLY_MAIN": "RLY_MAIN",
              "P_RLY_BUZZER": "RLY_BUZZER", "P_BOOST_DIS": "BOOST_DIS", "P_WDT_KICK": "WDT_KICK",
              "P_LED": "LED_STATUS", "P_IGNITION": "IN_IGNITION", "P_WIF": "IN_WIF", "P_DIAG": "SW_DIAG",
              "P_STOP": "SW_STOP", "P_DROOP": "SW_DROOP", "P_COOLANT_SW": "SW_COOLANT",
              "P_AUDIO_ABORT": "IN_AUDIO_ABORT", "P_OVERRIDE_SS": "IN_OVERRIDE_SS",
              "P_WDT_FAULT": "WDT_FAULT", "P_CRANK": "CRANK_EDGE", "P_CAM": "CAM_EDGE",
              "P_CAN1_RX": "CAN1_RX", "P_CAN1_TX": "CAN1_TX", "P_CAN2_RX": "CAN2_RX", "P_CAN2_TX": "CAN2_TX"}
    for macro, sig in sig_of.items():
        want = sp.ASSIGN[sig][0]
        if pins.get(macro) != want:
            bad.append(f"{macro}: board.h {pins.get(macro)}, stm32_pins.py {want}")
    for macro, sig, afm in (("P_MU_PWM", "MU_PWM", "AF_MU_PWM"), ("P_CRANK", "CRANK_EDGE", "AF_TIM2"),
                            ("P_CAM", "CAM_EDGE", "AF_TIM2"), ("P_CAN1_RX", "CAN1_RX", "AF_FDCAN"),
                            ("P_CAN1_TX", "CAN1_TX", "AF_FDCAN"), ("P_CAN2_RX", "CAN2_RX", "AF_FDCAN"),
                            ("P_CAN2_TX", "CAN2_TX", "AF_FDCAN")):
        pin, fn = sp.ASSIGN[sig]
        got = int(re.search(r"#define %s (\d+)u" % afm, BOARD).group(1))
        if af.get((pin, fn)) != got:
            bad.append(f"{afm}: board.h AF{got}, ST says AF{af.get((pin, fn))} for {fn} on {pin}")
    # the ADC channel lists
    for name, adc in (("ADC2_CHANNELS", "ADC2"), ("ADC3_CHANNELS", "ADC3")):
        chs = [int(x) for x in re.search(r"#define %s \{([^}]*)\}" % name, BOARD).group(1).split(",")]
        for ch in chs:
            if ch == 18:
                continue                                    # VREFINT, internal
            if not any(fn == f"{adc}_IN{ch}" or f"{adc}_IN{ch}" in sp.PINDATA[pin]["signals"]
                       for pin, fn in sp.ASSIGN.values() if fn.startswith("ADC")):
                bad.append(f"{name}: {adc}_IN{ch} is on no assigned analog pin")
    for ch, sig in ((3, "ISNS_INJ_A"), (4, "ISNS_INJ_B")):
        if sp.ASSIGN[sig][1] != f"ADC1_IN{ch}":
            bad.append(f"ADC1 channel {ch} is not {sig}")
    print("\n".join(bad) or f"  pins: {len(sig_of)} pins, 7 AF numbers and the ADC channels agree with ST")
    return not bad


def main():
    os.makedirs(OUT, exist_ok=True)
    print("STM32G474 build (zig)")
    app("app", [])
    standalone()
    app("app_model", ["-DECU_MODEL"])
    boot()
    ok = check_pins() if "--check" in sys.argv else True
    print("  outputs in firmware/stm32/build/")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
