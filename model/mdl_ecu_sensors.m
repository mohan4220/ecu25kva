function mdl_ecu_sensors(P)
%MDL_ECU_SENSORS  Sensor volts to engineering units, with debounced range
%   faults (firmware/core/sensors.c sens_step_1ms). Five channels: coolant,
%   oil, rail, boost, EGR position.
%
%   Each step: the 5 V reference with its end-of-line trim (outside
%   4.5-5.5 V the nominal 5 V is used); each input trimmed and made
%   ratiometric; above SENS_V_HI is FMI 3, below its own low limit FMI 4;
%   a change of fault state must hold SENS_FAULT_MS ticks; while faulted
%   the value is the channel's default. Coolant is an NTC (beta law), the
%   others 0.5-4.5 V linear spans. The trims are inputs: the end-of-line
%   record can change them at run time.
%
%   The state (debounce counts, latched FMIs, last values) is in three
%   Unit Delays, so the diagram shows what the chart remembers.
m = 'ecu_sensors';
mb.new(m);
S = 'single';
ins = {'v', S, 5; 'v_5v', S, 1; 'gain', S, 6; 'offset', S, 6};
for i = 1:size(ins, 1)
    h = mb.in(m, ins{i, 1}, ins{i, 2});
    set_param(h, 'PortDimensions', num2str(ins{i, 3}));
end
mb.out(m, 'val', S);
mb.out(m, 'fmi', 'uint8');

n = @(x) mb.num(single(x));
src = sprintf([ ...
 'function [val, fmi, bad_n, fmi_n, val_n] = convert(v, v_5v, gain, offset, bad, fmi_p, val_p)\n' ...
 '%%#codegen\n' ...
 'DEF = single(%s); VLO = single(%s); SLO = single(%s); SHI = single(%s);\n' ...
 'NT = single(%s); NR = single(%s);\n' ...
 'v5 = v_5v * gain(6) + offset(6);\n' ...
 'if ~(v5 >= single(4.5) && v5 <= single(5.5))   %% supply fault: use nominal\n' ...
 '    v5 = single(5);\n' ...
 'end\n' ...
 'bad_n = bad; fmi_n = fmi_p; val_n = val_p;\n' ...
 'for i = 1:5\n' ...
 '    vr = (v(i) * gain(i) + offset(i)) * single(5) / v5;\n' ...
 '    if ~(vr <= single(%s))                     %% NaN reads high\n' ...
 '        now = uint8(3);\n' ...
 '    elseif vr < VLO(i)\n' ...
 '        now = uint8(4);\n' ...
 '    else\n' ...
 '        now = uint8(0);\n' ...
 '    end\n' ...
 '    %% the count is time spent disagreeing with the latched state\n' ...
 '    if (now ~= 0) ~= (fmi_n(i) ~= 0)\n' ...
 '        bad_n(i) = bad_n(i) + uint16(1);\n' ...
 '        if bad_n(i) >= uint16(%d)\n' ...
 '            fmi_n(i) = now;\n' ...
 '            bad_n(i) = uint16(0);\n' ...
 '        end\n' ...
 '    else\n' ...
 '        bad_n(i) = uint16(0);\n' ...
 '        if now ~= 0\n' ...
 '            fmi_n(i) = now;\n' ...
 '        end\n' ...
 '    end\n' ...
 '    %% faulted: the default; out of range but not yet latched: hold\n' ...
 '    if fmi_n(i) ~= 0\n' ...
 '        val_n(i) = DEF(i);\n' ...
 '    elseif now == 0\n' ...
 '        if i == 1                              %% coolant NTC, Bosch table in ln(R)\n' ...
 '            r = single(%s) * vr / (single(5) - vr);\n' ...
 '            if r < single(%s)\n' ...
 '                r = r * single(%s) / (single(%s) - r);\n' ...
 '            else\n' ...
 '                r = single(1e9);\n' ...
 '            end\n' ...
 '            if ~(r < NR(1))\n' ...
 '                val_n(i) = NT(1);\n' ...
 '            elseif r <= NR(20)\n' ...
 '                val_n(i) = NT(20);\n' ...
 '            else\n' ...
 '                k = int32(1);\n' ...
 '                while r <= NR(k + 1)\n' ...
 '                    k = k + int32(1);\n' ...
 '                end\n' ...
 '                val_n(i) = NT(k) + (NT(k + 1) - NT(k)) * (log(NR(k) / r) / log(NR(k) / NR(k + 1)));\n' ...
 '            end\n' ...
 '        else\n' ...
 '            val_n(i) = SLO(i) + (vr - single(0.5)) / single(4) * (SHI(i) - SLO(i));\n' ...
 '        end\n' ...
 '    end\n' ...
 'end\n' ...
 'val = val_n; fmi = fmi_n;\n'], ...
 n(P.sens_default), n(P.sens_v_lo), n(P.span_lo), n(P.span_hi), n(P.ntc_t), n(P.ntc_r), n(P.SENS_V_HI), ...
 P.SENS_FAULT_MS, n(P.NTC_PULLUP), n(P.NTC_LOAD), n(P.NTC_LOAD), n(P.NTC_LOAD));
mfun(m, 'convert', src, containers.Map( ...
    {'v', 'v_5v', 'gain', 'offset', 'bad', 'fmi_p', 'val_p', 'val', 'fmi', 'bad_n', 'fmi_n', 'val_n'}, ...
    {S, S, S, S, 'uint16', 'uint8', S, S, 'uint8', 'uint16', 'uint8', S}));
mb.b(m, 'bad_z', 'simulink/Discrete/Unit Delay', 'InitialCondition', 'zeros(5,1)');
mb.b(m, 'fmi_z', 'simulink/Discrete/Unit Delay', 'InitialCondition', 'zeros(5,1)');
mb.b(m, 'val_z', 'simulink/Discrete/Unit Delay', 'InitialCondition', n(P.sens_default(:)));
set_param([m '/bad_z'], 'SampleTime', '-1');
set_param([m '/fmi_z'], 'SampleTime', '-1');
set_param([m '/val_z'], 'SampleTime', '-1');
mb.l(m, 'v/1', 'convert/1'); mb.l(m, 'v_5v/1', 'convert/2');
mb.l(m, 'gain/1', 'convert/3'); mb.l(m, 'offset/1', 'convert/4');
mb.l(m, 'bad_z/1', 'convert/5'); mb.l(m, 'fmi_z/1', 'convert/6'); mb.l(m, 'val_z/1', 'convert/7');
mb.l(m, 'convert/3', 'bad_z/1'); mb.l(m, 'convert/4', 'fmi_z/1'); mb.l(m, 'convert/5', 'val_z/1');
mb.l(m, 'convert/1', 'val/1'); mb.l(m, 'convert/2', 'fmi/1');
set_param(m, 'Description', 'Sensor conversion and range faults. Source of truth for firmware/gen/ecu_sensors.');
mb.finish(m);
end
