function mdl_ecu_mucur(P)
%MDL_ECU_MUCUR  The metering valve's inner loop (firmware/core/actuate.c
%   mu_step): the cascade's second stage, after the 20 kVA set's cascade
%   PID (decisions log 23). The rail PI's output is a current command in
%   units of MU_I_FULL; this feeds the battery voltage forward and closes
%   on the coil current (ISNS_MU), so a hot coil or a low battery does not
%   move the valve. Without a measurement: feedforward only. The integral
%   stops while the output is driven into a limit.
m = 'ecu_mucur';
mb.new(m);
S = 'single';
mb.in(m, 'cmd', S); mb.in(m, 'i_meas', S); mb.in(m, 'valid', 'uint8'); mb.in(m, 'v_bat', S);
mb.out(m, 'duty', S);
n = @(x) mb.num(single(x));
src = sprintf([ ...
 'function [duty, integ_n] = loop(cmd, i_meas, valid, v_bat, integ)\n' ...
 '%%#codegen\n' ...
 'if v_bat >= single(%s) && v_bat <= single(%s)\n' ...
 '    vb = v_bat;\n' ...
 'else\n' ...
 '    vb = single(%s);                       %% no plausible reading: nominal\n' ...
 'end\n' ...
 'ff = cmd * (single(%s) / vb);               %% a nominal coil carries cmd * MU_I_FULL\n' ...
 'if valid == 0\n' ...
 '    integ_n = single(0);\n' ...
 '    duty = sat(ff, single(0), single(1));\n' ...
 '    return\n' ...
 'end\n' ...
 'err = cmd - i_meas / single(%s);   %% in units of the full current\n' ...
 'out = ff + integ + single(%s) * err;\n' ...
 'integ_n = integ;\n' ...
 'if ~((out >= single(1) && err > single(0)) || (out <= single(0) && err < single(0)))\n' ...
 '    integ_n = sat(integ + single(%s) * err * single(%s), single(-%s), single(%s));\n' ...
 'end\n' ...
 'duty = sat(ff + integ_n + single(%s) * err, single(0), single(1));\n' ...
 'end\n' ...
 '\n' ...
 'function y = sat(x, lo, hi)\n' ...
 'if x < lo\n' ...
 '    y = lo;\n' ...
 'elseif x > hi\n' ...
 '    y = hi;\n' ...
 'else\n' ...
 '    y = x;\n' ...
 'end\n' ...
 'end\n'], ...
 n(P.MU_VBAT_MIN), n(P.MU_VBAT_MAX), n(P.MU_V_NOM), n(P.MU_V_FULL), n(P.MU_I_FULL), ...
 n(P.MU_KP), n(P.MU_KI), n(P.DT), n(P.MU_INTEG_MAX), n(P.MU_INTEG_MAX), n(P.MU_KP));
mfun(m, 'loop', src, containers.Map({'cmd', 'i_meas', 'valid', 'v_bat', 'integ', 'duty', 'integ_n'}, ...
    {S, S, 'uint8', S, S, S, S}));
mb.b(m, 'integ_z', 'simulink/Discrete/Unit Delay', 'InitialCondition', '0');
mb.l(m, 'cmd/1', 'loop/1'); mb.l(m, 'i_meas/1', 'loop/2'); mb.l(m, 'valid/1', 'loop/3');
mb.l(m, 'v_bat/1', 'loop/4'); mb.l(m, 'integ_z/1', 'loop/5');
mb.l(m, 'loop/2', 'integ_z/1'); mb.l(m, 'loop/1', 'duty/1');
set_param(m, 'Description', 'Metering valve current loop. Source of truth for firmware/gen/ecu_mucur.');
mb.finish(m);
end
