function mdl_ecu_crank(P)
%MDL_ECU_CRANK  The 60-2 crank decoder and the cam-wheel learning
%   (firmware/core/crank.c crank_edge, crank_cam, crank_poll; decisions log
%   39, 41). One step per event: ev 0 a crank tooth edge, 1 a cam edge,
%   2 a timeout poll, each at t_us.
%
%   Teeth: a tooth under half the previous tooth's time is noise and
%   dropped; one over 1.5x the previous is the gap; two gaps exactly 58
%   teeth apart is sync; a gap out of place, a gap missing, or no tooth
%   for CRANK_TIMEOUT_US loses it. Cam: each revolution's cam edges are
%   summed up (how many, the tooth of the first and of the last); two
%   whole revolutions that differ teach the wheel, the one with more edges
%   (then the earlier first, then the earlier last) is the marker and the
%   revolution after it rev 0; a revolution matching neither drops the
%   phase. See crank.h for the whole rule.
%
%   Stateless: the decoder's state comes in and goes out as two packed
%   vectors (u32: last_us, prev_period, per[6]; u8: deg[6], nper, head,
%   have, count, gap_seen, synced, phased, rev, fault, prev_gap, the cur /
%   prev / mark / other signatures, prev_ok, learned, proven, miss,
%   clean), so crank_t is the same in both builds. The C's unsigned
%   wraparound, truncating division and uint8 roll-over are reproduced.
m = 'ecu_crank';
mb.new(m);
U8 = 'uint8'; U32 = 'uint32';
mb.in(m, 'ev', U8); mb.in(m, 't_us', U32);
h = mb.in(m, 'a_in', U32); set_param(h, 'PortDimensions', '8');
h = mb.in(m, 'b_in', U8); set_param(h, 'PortDimensions', '33');
mb.out(m, 'a', U32); mb.out(m, 'b', U8);
EDGES = P.CRANK_TEETH - 2;
src = sprintf([ ...
 'function [a, b] = step(ev, t_us, a_in, b_in)\n' ...
 '%%#codegen\n' ...
 'a = a_in; b = b_in;\n' ...
 'EDGES = uint8(%d); WIN = uint8(%d); TMO = uint32(%d); TOL = uint8(%d); MISS = uint8(%d);\n' ...
 'F_GAP = uint8(%d); F_TMO = uint8(%d);\n' ...
 'if ev == uint8(0)\n' ...
 '    if b(9) == 0                                    %% have\n' ...
 '        b(9) = uint8(1); a(1) = t_us;\n' ...
 '    else\n' ...
 '        period = since(t_us, a(1));\n' ...
 '        if period > TMO\n' ...
 '            b = lose(b, F_TMO);\n' ...
 '            a(2) = uint32(0); b(7) = uint8(0); b(8) = uint8(0);   %% prev_period, nper, head\n' ...
 '            b(11) = uint8(0); b(10) = uint8(0); b(16) = uint8(0); %% gap_seen, count, prev_gap\n' ...
 '            a(1) = t_us;\n' ...
 '        else\n' ...
 '            if b(16) ~= 0\n' ...
 '                tp = idivide(a(2), uint32(3), ''floor'');\n' ...
 '            else\n' ...
 '                tp = a(2);\n' ...
 '            end\n' ...
 '            if ~(period < idivide(tp, uint32(2), ''floor''))    %% else noise: dropped, no change\n' ...
 '                gap = a(2) ~= 0 && period > a(2) + idivide(a(2), uint32(2), ''floor'');\n' ...
 '                hd = int32(b(8));\n' ...
 '                a(3 + hd) = period;\n' ...
 '                if gap\n' ...
 '                    b(1 + hd) = uint8(18);\n' ...
 '                else\n' ...
 '                    b(1 + hd) = uint8(6);\n' ...
 '                end\n' ...
 '                b(8) = uint8(mod(hd + int32(1), int32(WIN)));\n' ...
 '                if b(7) < WIN, b(7) = b(7) + uint8(1); end\n' ...
 '                if gap\n' ...
 '                    in_place = b(11) ~= 0 && b(10) == EDGES - uint8(1);\n' ...
 '                    if ~in_place\n' ...
 '                        b = lose(b, F_GAP);\n' ...
 '                    elseif b(12) == 0\n' ...
 '                        b(12) = uint8(1);\n' ...
 '                    end\n' ...
 '                    b(11) = uint8(1); b(10) = uint8(0);\n' ...
 '                    b = cam_at_gap(b, in_place, TOL, MISS);\n' ...
 '                    b(17) = uint8(0); b(18) = uint8(0); b(19) = uint8(0);\n' ...
 '                else\n' ...
 '                    b(10) = uint8(mod(int32(b(10)) + int32(1), int32(256)));   %% uint8 wraps, as in C\n' ...
 '                    if b(10) >= EDGES\n' ...
 '                        b = lose(b, F_GAP);\n' ...
 '                        b(11) = uint8(0);\n' ...
 '                    end\n' ...
 '                end\n' ...
 '                a(1) = t_us; a(2) = period; b(16) = uint8(gap);\n' ...
 '            end\n' ...
 '        end\n' ...
 '    end\n' ...
 'elseif ev == uint8(1)\n' ...
 '    if b(17) == 0, b(18) = b(10); end\n' ...
 '    b(19) = b(10);\n' ...
 '    if b(17) < uint8(255), b(17) = b(17) + uint8(1); end\n' ...
 'elseif ev == uint8(2)\n' ...
 '    d = since(t_us, a(1));\n' ...
 '    %% as C''s (int32_t)(t - last) > TIMEOUT: over it, and positive as a signed value\n' ...
 '    if b(12) ~= 0 && d > TMO && d <= uint32(2147483647)\n' ...
 '        b = lose(b, F_TMO);\n' ...
 '    end\n' ...
 'end\n' ...
 '\n' ...
 'function d = since(t, last)                      %% t - last, wrapping as uint32_t does\n' ...
 'if t >= last\n    d = t - last;\nelse\n    d = (t + (intmax(''uint32'') - last)) + uint32(1);   %% neither sum can saturate\nend\n' ...
 '\n' ...
 'function b = lose(b, why)\n' ...
 'if b(12) ~= 0, b(15) = why; end\n' ...
 'b(12) = uint8(0); b(13) = uint8(0); b(7) = uint8(0);\n' ...
 '\n' ...
 'function y = near(x, z, TOL)\n' ...
 'if x > z\n    y = (x - z) <= TOL;\nelse\n    y = (z - x) <= TOL;\nend\n' ...
 '\n' ...
 'function y = sig_match(s, r, TOL)                %% s, r: [n first last]\n' ...
 'y = s(1) == r(1) && (s(1) == 0 || (near(s(2), r(2), TOL) && near(s(3), r(3), TOL)));\n' ...
 '\n' ...
 'function k = sig_marker(s, r, TOL)               %% 1: s, 0: r, -1: too alike\n' ...
 'if s(1) ~= r(1)\n    k = int8(s(1) > r(1));\n' ...
 'elseif s(1) == 0\n    k = int8(-1);\n' ...
 'elseif ~near(s(2), r(2), TOL)\n    k = int8(s(2) < r(2));\n' ...
 'elseif ~near(s(3), r(3), TOL)\n    k = int8(s(3) < r(3));\n' ...
 'else\n    k = int8(-1);\nend\n' ...
 '\n' ...
 'function b = cam_at_gap(b, whole, TOL, MISS)\n' ...
 '%% b(17:19) cur, 20:22 prev, 23:25 mark, 26:28 other; 29 prev_ok, 30 learned,\n' ...
 '%% 31 proven, 32 miss, 33 clean; 12 synced, 13 phased, 14 rev\n' ...
 'if ~whole\n' ...
 '    b(29) = uint8(0); b(14) = bitxor(b(14), uint8(1));\n' ...
 '    return;\n' ...
 'end\n' ...
 'nxt = int8(-1); missed = false;\n' ...
 'cur = b(17:19); prv = b(20:22);\n' ...
 'if b(30) ~= 0\n' ...
 '    if sig_match(cur, b(23:25), TOL)\n' ...
 '        nxt = int8(0);\n' ...
 '    elseif sig_match(cur, b(26:28), TOL)\n' ...
 '        nxt = int8(1);\n' ...
 '    end\n' ...
 '    if nxt < 0\n' ...
 '        missed = true; b(33) = uint8(0);\n' ...
 '        if b(31) == 0\n' ...
 '            b(30) = uint8(0);\n' ...
 '        else\n' ...
 '            b(32) = uint8(mod(int32(b(32)) + int32(1), int32(256)));\n' ...
 '            if b(32) >= MISS, b(30) = uint8(0); end\n' ...
 '        end\n' ...
 '    else\n' ...
 '        b(33) = uint8(mod(int32(b(33)) + int32(1), int32(256)));\n' ...
 '        if b(33) >= uint8(2)\n' ...
 '            b(33) = uint8(2); b(31) = uint8(1); b(32) = uint8(0);\n' ...
 '        end\n' ...
 '    end\n' ...
 'end\n' ...
 'if b(30) == 0 && b(29) ~= 0 && ~missed\n' ...
 '    k = sig_marker(cur, prv, TOL);\n' ...
 '    if k >= 0\n' ...
 '        if k ~= 0\n' ...
 '            b(23:25) = cur; b(26:28) = prv; nxt = int8(0);\n' ...
 '        else\n' ...
 '            b(23:25) = prv; b(26:28) = cur; nxt = int8(1);\n' ...
 '        end\n' ...
 '        b(30) = uint8(1); b(31) = uint8(0); b(32) = uint8(0); b(33) = uint8(0);\n' ...
 '    end\n' ...
 'end\n' ...
 'if nxt < 0\n' ...
 '    b(13) = uint8(0); b(14) = bitxor(b(14), uint8(1));\n' ...
 'else\n' ...
 '    agrees = b(13) == 0 || b(14) == bitxor(uint8(nxt), uint8(1));\n' ...
 '    b(14) = uint8(nxt);\n' ...
 '    b(13) = uint8(b(12) ~= 0 && agrees);\n' ...
 'end\n' ...
 'b(20:22) = cur;\n' ...
 'b(29) = uint8(~missed);\n'], ...
 EDGES, P.CRANK_WIN, P.CRANK_TIMEOUT_US, P.CRANK_CAM_TOL, P.CRANK_CAM_MISS, P.CRANK_F_GAP, P.CRANK_F_TIMEOUT);
mfun(m, 'step', src, containers.Map({'ev', 't_us', 'a_in', 'b_in', 'a', 'b'}, {U8, U32, U32, U8, U32, U8}));
mb.l(m, 'ev/1', 'step/1'); mb.l(m, 't_us/1', 'step/2'); mb.l(m, 'a_in/1', 'step/3'); mb.l(m, 'b_in/1', 'step/4');
mb.l(m, 'step/1', 'a/1'); mb.l(m, 'step/2', 'b/1');
set_param(m, 'Description', 'Crank decoder and cam-wheel learning. Source of truth for firmware/gen/ecu_crank.');
mb.finish(m);
end
