function mdl_ecu_muclose(P)
%MDL_ECU_MUCLOSE  The duty that holds the metering valve closed on the
%   learned coil (firmware/core/actuate.c mu_close_duty: mu_ff of
%   mu_fallback_cmd(METER_CLOSED, r); decisions log 34, 41). Used for one
%   tick at the trip and the reset, before the current loop takes over.
%   The learned ohms clamped to MU_R_LO..MU_R_HI scale the closing command;
%   the duty is that command times MU_V_FULL over the battery (MU_V_NOM
%   outside MU_VBAT_MIN..MU_VBAT_MAX), clamped to 0..1.
m = 'ecu_muclose';
mb.new(m);
S = 'single';
mb.in(m, 'r', S); mb.in(m, 'v_bat', S);
mb.out(m, 'duty', S);
n = @(x) mb.num(single(x));
src = sprintf([ ...
 'function duty = close(r, v_bat)\n' ...
 '%%#codegen\n' ...
 'rc = r;\n' ...
 'if rc < single(%s)\n' ...
 '    rc = single(%s);\n' ...
 'elseif rc > single(%s)\n' ...
 '    rc = single(%s);\n' ...
 'end\n' ...
 'c = single(%s) * (rc / single(%s));\n' ...
 'if v_bat >= single(%s) && v_bat <= single(%s)\n' ...
 '    vb = v_bat;\n' ...
 'else\n' ...
 '    vb = single(%s);\n' ...
 'end\n' ...
 'duty = c * (single(%s) / vb);\n' ...
 'if duty < single(0)\n' ...
 '    duty = single(0);\n' ...
 'elseif duty > single(1)\n' ...
 '    duty = single(1);\n' ...
 'end\n'], ...
 n(P.MU_R_LO), n(P.MU_R_LO), n(P.MU_R_HI), n(P.MU_R_HI), n(P.METER_CLOSED), n(P.MU_R_NOM), ...
 n(P.MU_VBAT_MIN), n(P.MU_VBAT_MAX), n(P.MU_V_NOM), n(P.MU_V_FULL));
mfun(m, 'close', src, containers.Map({'r', 'v_bat', 'duty'}, {S, S, S}));
mb.l(m, 'r/1', 'close/1'); mb.l(m, 'v_bat/1', 'close/2'); mb.l(m, 'close/1', 'duty/1');
set_param(m, 'Description', 'Closed-valve duty on the learned coil. Source of truth for firmware/gen/ecu_muclose.');
mb.finish(m);
end
