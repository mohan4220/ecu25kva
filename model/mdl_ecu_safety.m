function mdl_ecu_safety(P)
%MDL_ECU_SAFETY  The trip decision (firmware/core/safety.c safety_check):
%   overspeed first, then a crank fault while running, then ignition off.
m = 'ecu_safety';
mb.new(m);
mb.in(m, 'rpm', 'single'); mb.in(m, 'crank_fault', 'uint8');
mb.in(m, 'ignition', 'uint8'); mb.in(m, 'running', 'uint8');
mb.out(m, 'why', 'uint8');
src = sprintf([ ...
 'function why = decide(rpm, crank_fault, ignition, running)\n' ...
 '%%#codegen\n' ...
 '%% TRIP_NONE 0, TRIP_OVERSPEED 1, TRIP_SYNC 2, TRIP_IGN 3 (safety.h)\n' ...
 'if rpm > single(%s)\n' ...
 '    why = uint8(1);\n' ...
 'elseif running ~= 0 && crank_fault ~= 0\n' ...
 '    why = uint8(2);\n' ...
 'elseif ignition == 0\n' ...
 '    why = uint8(3);\n' ...
 'else\n' ...
 '    why = uint8(0);\n' ...
 'end\n'], mb.num(P.OVERSPEED_RPM));
mfun(m, 'decide', src, containers.Map({'rpm', 'crank_fault', 'ignition', 'running', 'why'}, ...
    {'single', 'uint8', 'uint8', 'uint8', 'uint8'}));
mb.l(m, 'rpm/1', 'decide/1'); mb.l(m, 'crank_fault/1', 'decide/2');
mb.l(m, 'ignition/1', 'decide/3'); mb.l(m, 'running/1', 'decide/4');
mb.l(m, 'decide/1', 'why/1');
set_param(m, 'Description', 'Trip decision. Source of truth for firmware/gen/ecu_safety.');
mb.finish(m);
end
