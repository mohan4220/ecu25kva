function mdl_ecu_musup(P)
%MDL_ECU_MUSUP  The metering valve's supervision, one tick
%   (firmware/core/actuate.c mu_sup_step; decisions log 34, 41).
%
%   Whether the coil-current reading is trusted, and what to command when
%   it is not:
%   - a reading is impossible while the coil is driven hard enough that
%     even the highest coil (DG_MU_R_HI) would carry DG_MU_EXPECT_A yet it
%     reads under DG_MU_OPEN_A, or whenever it reads over DG_MU_MAX_A;
%     after MU_DISTRUST_MS such ticks it is no longer trusted, nor while
%     either DTC (1347/5, 1347/6) is active;
%   - trusted, the coil's resistance is learned from it (duty x battery /
%     current, clamped to MU_R_LO..MU_R_HI, filtered by MU_R_ALPHA), only
%     on a plausible battery, above MU_R_LEARN_A and away from 0 / 100 %;
%   - not trusted, the command is scaled by the learned resistance over
%     MU_R_NOM, so feedforward alone drives the real coil.
%   Stateless: the learned ohms and the distrust count come in (r_p,
%   bad_p) and go out (r_n, bad_n); the caller keeps them (mu_sup_t).
m = 'ecu_musup';
mb.new(m);
S = 'single'; U8 = 'uint8'; U16 = 'uint16';
ins = {'cmd', S; 'duty_prev', S; 'v_bat', S; 'i_mu', S; 'i_valid', U8; ...
       'act_open', U8; 'act_over', U8; 'r_p', S; 'bad_p', U16};
outs = {'cmd_out', S; 'meas', U8; 'r_n', S; 'bad_n', U16};
for i = 1:size(ins, 1), mb.in(m, ins{i, 1}, ins{i, 2}); end
for i = 1:size(outs, 1), mb.out(m, outs{i, 1}, outs{i, 2}); end
n = @(x) mb.num(single(x));
src = sprintf([ ...
 'function [cmd_out, meas, r_n, bad_n] = sup(cmd, duty_prev, v_bat, i_mu, i_valid, act_open, act_over, r_p, bad_p)\n' ...
 '%%#codegen\n' ...
 '%% impossible: driven, yet (almost) no current; or more than any coil could draw\n' ...
 'odd = i_valid ~= 0 && ((duty_prev * v_bat / single(%s) > single(%s) && i_mu < single(%s)) ...\n' ...
 '                       || i_mu > single(%s));\n' ...
 'if odd\n' ...
 '    if bad_p < uint16(65535)\n' ...
 '        bad_n = bad_p + uint16(1);\n' ...
 '    else\n' ...
 '        bad_n = bad_p;\n' ...
 '    end\n' ...
 'else\n' ...
 '    bad_n = uint16(0);\n' ...
 'end\n' ...
 'trusted = i_valid ~= 0 && bad_n < uint16(%d) && act_open == 0 && act_over == 0;\n' ...
 'meas = uint8(trusted);\n' ...
 'r_n = r_p;\n' ...
 'if trusted\n' ...
 '    %% learn: a plausible battery, enough current, the duty away from its ends\n' ...
 '    if (v_bat >= single(%s) && v_bat <= single(%s)) && i_mu >= single(%s) ...\n' ...
 '            && duty_prev > single(0.05) && duty_prev < single(0.95)\n' ...
 '        x = duty_prev * v_bat / i_mu;\n' ...
 '        if x < single(%s)\n' ...
 '            x = single(%s);\n' ...
 '        elseif x > single(%s)\n' ...
 '            x = single(%s);\n' ...
 '        end\n' ...
 '        r_n = r_p + (x - r_p) * single(%s);\n' ...
 '    end\n' ...
 '    cmd_out = cmd;\n' ...
 'else\n' ...
 '    %% the fallback: the command scaled to the learned coil\n' ...
 '    r = r_n;\n' ...
 '    if r < single(%s)\n' ...
 '        r = single(%s);\n' ...
 '    elseif r > single(%s)\n' ...
 '        r = single(%s);\n' ...
 '    end\n' ...
 '    cmd_out = cmd * (r / single(%s));\n' ...
 'end\n'], ...
 n(P.DG_MU_R_HI), n(P.DG_MU_EXPECT_A), n(P.DG_MU_OPEN_A), n(P.DG_MU_MAX_A), P.MU_DISTRUST_MS, ...
 n(P.MU_VBAT_MIN), n(P.MU_VBAT_MAX), n(P.MU_R_LEARN_A), ...
 n(P.MU_R_LO), n(P.MU_R_LO), n(P.MU_R_HI), n(P.MU_R_HI), n(P.MU_R_ALPHA), ...
 n(P.MU_R_LO), n(P.MU_R_LO), n(P.MU_R_HI), n(P.MU_R_HI), n(P.MU_R_NOM));
types = containers.Map([ins(:, 1); outs(:, 1)]', [ins(:, 2); outs(:, 2)]');
mfun(m, 'sup', src, types);
for i = 1:size(ins, 1), mb.l(m, sprintf('%s/1', ins{i, 1}), sprintf('sup/%d', i)); end
for i = 1:size(outs, 1), mb.l(m, sprintf('sup/%d', i), sprintf('%s/1', outs{i, 1})); end
set_param(m, 'Description', ['Metering valve supervision: trust, coil learning, fallback. ' ...
    'Source of truth for firmware/gen/ecu_musup.']);
mb.finish(m);
end
