function mdl_ecu_egrpos(P)
%MDL_ECU_EGRPOS  The EGR valve's position loop (firmware/core/actuate.c
%   egrp_step): the inner PID of the 20 kVA set's cascade (decisions log
%   23) on the valve's own position sensor (pin 37). P on the error, I with
%   the integral stopped while saturated, D on the MEASUREMENT (no kick
%   when the target steps) through a first-order filter. At or below
%   EGR_CLOSED_PCT, or not enabled, the bridge coasts: the spring closes
%   the valve, and driving into the closed stop would only stall it.
m = 'ecu_egrpos';
mb.new(m);
S = 'single';
mb.in(m, 'target', S); mb.in(m, 'pos', S); mb.in(m, 'enable', 'uint8');
mb.out(m, 'duty', S);
n = @(x) mb.num(single(x));
src = sprintf([ ...
 'function [duty, integ_n, prev_n, dfilt_n] = pid(target, pos, enable, integ, prev, dfilt)\n' ...
 '%%#codegen\n' ...
 'dpos = (pos - prev) / single(%s);\n' ...
 'prev_n = pos;\n' ...
 'if enable == 0 || target <= single(%s)          %% coast: the spring closes it\n' ...
 '    integ_n = single(0); dfilt_n = single(0); duty = single(0);\n' ...
 '    return\n' ...
 'end\n' ...
 'dfilt_n = dfilt + single(%s) * (dpos - dfilt);\n' ...
 'err = target - pos;\n' ...
 'out = single(%s) * err + integ - single(%s) * dfilt_n;\n' ...
 'integ_n = integ;\n' ...
 'if ~((out >= single(%s) && err > single(0)) || (out <= single(-%s) && err < single(0)))\n' ...
 '    integ_n = sat(integ + single(%s) * err * single(%s), single(-%s), single(%s));\n' ...
 'end\n' ...
 'duty = sat(single(%s) * err + integ_n - single(%s) * dfilt_n, single(-%s), single(%s));\n' ...
 'end\n' ...
 '\n' ...
 'function y = sat(x, lo, hi)\n' ...
 'if x < lo\n' ...
 '    y = lo;\n' ...
 'elseif x > hi\n' ...
 '    y = hi;\n' ...
 'else\n' ...
 '    y = x;\n' ...
 'end\n' ...
 'end\n'], ...
 n(P.DT), n(P.EGR_CLOSED_PCT), n(P.EGR_D_ALPHA), n(P.EGR_KP), n(P.EGR_KD), ...
 n(P.EGR_DUTY_MAX), n(P.EGR_DUTY_MAX), n(P.EGR_KI), n(P.DT), n(P.EGR_DUTY_MAX), n(P.EGR_DUTY_MAX), ...
 n(P.EGR_KP), n(P.EGR_KD), n(P.EGR_DUTY_MAX), n(P.EGR_DUTY_MAX));
mfun(m, 'pid', src, containers.Map({'target', 'pos', 'enable', 'integ', 'prev', 'dfilt', ...
    'duty', 'integ_n', 'prev_n', 'dfilt_n'}, {S, S, 'uint8', S, S, S, S, S, S, S}));
for z = {'integ_z', 'prev_z', 'dfilt_z'}
    mb.b(m, z{1}, 'simulink/Discrete/Unit Delay', 'InitialCondition', '0');
end
mb.l(m, 'target/1', 'pid/1'); mb.l(m, 'pos/1', 'pid/2'); mb.l(m, 'enable/1', 'pid/3');
mb.l(m, 'integ_z/1', 'pid/4'); mb.l(m, 'prev_z/1', 'pid/5'); mb.l(m, 'dfilt_z/1', 'pid/6');
mb.l(m, 'pid/2', 'integ_z/1'); mb.l(m, 'pid/3', 'prev_z/1'); mb.l(m, 'pid/4', 'dfilt_z/1');
mb.l(m, 'pid/1', 'duty/1');
set_param(m, 'Description', 'EGR valve position PID. Source of truth for firmware/gen/ecu_egrpos.');
mb.finish(m);
end
