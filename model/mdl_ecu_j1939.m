function mdl_ecu_j1939(P)
%MDL_ECU_J1939  The periodic J1939 PGNs' data bytes, from the signals
%   (firmware/core/j1939.c): "Set PGNs". Sending them, the transport
%   protocol, DM1/DM2/DM4 and requests stay in C: byte-level protocol.
%
%   EEC1  61444  SPN 190 engine speed, 0.125 rpm/bit, bytes 4-5
%   ET1   65262  SPN 110 coolant, 1 degC/bit, -40 offset, byte 1
%   EFL/P1 65263 SPN 100 oil pressure, 4 kPa/bit, byte 4
%   HOURS 65253  SPN 247 engine hours, 0.05 h/bit, bytes 1-4
%   Unused bytes 0xFF; a failed sensor sends 0xFF ("not available").
m = 'ecu_j1939';
mb.new(m);
S = 'single'; U8 = 'uint8';
ins = {'rpm', S; 'clt_c', S; 'clt_ok', U8; 'oil_kpa', S; 'oil_ok', U8; 'engine_s', 'uint32'};
for i = 1:size(ins, 1)
    mb.in(m, ins{i, 1}, ins{i, 2});
end
outs = {'eec1', 'et1', 'eflp1', 'hours'};
for i = 1:numel(outs)
    mb.out(m, outs{i}, U8);
end
src = sprintf([ ...
 'function [eec1, et1, eflp1, hours] = pgns(rpm, clt_c, clt_ok, oil_kpa, oil_ok, engine_s)\n' ...
 '%%#codegen\n' ...
 'eec1 = repmat(uint8(255), 8, 1); et1 = eec1; eflp1 = eec1; hours = eec1;\n' ...
 '%% EEC1: speed, 0.125 rpm/bit, limited to the 8031.875 rpm range\n' ...
 'r = rpm;\n' ...
 'if r < single(0)\n' ...
 '    r = single(0);\n' ...
 'elseif r > single(8031)\n' ...
 '    r = single(8031);\n' ...
 'end\n' ...
 'raw = uint16(floor(r / single(0.125) + single(0.5)));\n' ...
 'eec1(4) = uint8(bitand(raw, uint16(255)));\n' ...
 'eec1(5) = uint8(bitshift(raw, -8));\n' ...
 'if clt_ok ~= 0\n' ...
 '    et1(1) = byte_clamp(clt_c + single(40));\n' ...
 'end\n' ...
 'if oil_ok ~= 0\n' ...
 '    eflp1(4) = byte_clamp(oil_kpa / single(4));\n' ...
 'end\n' ...
 '%% HOURS: 0.05 h = 180 s per bit, little-endian\n' ...
 'h = idivide(engine_s, uint32(180));\n' ...
 'for i = 1:4\n' ...
 '    hours(i) = uint8(bitand(bitshift(h, -8 * (i - 1)), uint32(255)));\n' ...
 'end\n' ...
 'end\n' ...
 '\n' ...
 'function b = byte_clamp(x)\n' ...
 '%% 0..250, rounded half up (250 and above are reserved in J1939)\n' ...
 'if x < single(0)\n' ...
 '    b = uint8(0);\n' ...
 'elseif x > single(250)\n' ...
 '    b = uint8(250);\n' ...
 'else\n' ...
 '    b = uint8(floor(x + single(0.5)));\n' ...
 'end\n' ...
 'end\n']);
mfun(m, 'set_pgns', src, containers.Map( ...
    {'rpm', 'clt_c', 'clt_ok', 'oil_kpa', 'oil_ok', 'engine_s', 'eec1', 'et1', 'eflp1', 'hours'}, ...
    {S, S, U8, S, U8, 'uint32', U8, U8, U8, U8}));
for i = 1:size(ins, 1)
    mb.l(m, [ins{i, 1} '/1'], sprintf('set_pgns/%d', i));
end
for i = 1:numel(outs)
    mb.l(m, sprintf('set_pgns/%d', i), [outs{i} '/1']);
end
set_param(m, 'Description', 'J1939 periodic PGN data. Source of truth for firmware/gen/ecu_j1939.');
mb.finish(m);
end
