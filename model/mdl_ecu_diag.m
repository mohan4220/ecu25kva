function mdl_ecu_diag(P)
%MDL_ECU_DIAG  The engine-side diagnoses and the coolant protection
%   (firmware/core/diag.c diag_cond; decisions log 24, 34, 35). Pure: one
%   tick's measurements in, one condition per fault out, no state and no
%   time. Each condition is debounced and healed by its own ecu_deb in
%   ecu.c, which raises or drops the DTC.
%
%   The 14 conditions, in diag.h's order:
%     1 EGR open load          2791/5    8 speed erratic        190/8
%     2 EGR stuck open         2791/0    9 oil at rest          100/2
%     3 EGR stuck shut         2791/7   10 battery high         168/16
%     4 metering valve open    1347/5   11 battery low          168/18
%     5 metering over current  1347/6   12 coolant hot, warn    110/16
%     6 rail deviation         157/7    13 coolant too hot, STOP 110/0
%     7 speed high             190/16   14 coolant level low    111/18
%   Every threshold is diag.h's, read by ecu_params. The battery and
%   coolant thresholds take the return level while their fault is active
%   (the *_act inputs), so a reading on the line does not chatter.
m = 'ecu_diag';
mb.new(m);
S = 'single'; U = 'uint8';
ins = {'running', U; 'ign_on', U; 'stopped', U; 'rpm', S; 'v_bat', S; ...
       'egr_duty', S; 'i_egr_f', S; 'egr_pos', S; 'egr_pos_ok', U; 'egr_off', U; ...
       'mu_duty', S; 'i_mu', S; 'i_mu_valid', U; ...
       'rail_set', S; 'rail_bar', S; 'rail_ok', U; ...
       'oil_kpa', S; 'oil_ok', U; 'bat_high_act', U; 'bat_low_act', U; ...
       'clt_c', S; 'clt_ok', U; 'clt_low', U; 'clt_warn_act', U; 'clt_stop_act', U};
for i = 1:size(ins, 1)
    mb.in(m, ins{i, 1}, ins{i, 2});
end
mb.out(m, 'c', U);

n = @(x) mb.num(single(x));
args = strjoin(ins(:, 1)', ', ');
src = sprintf([ ...
 'function c = cond(%s)\n' ...
 '%%#codegen\n' ...
 'c = zeros(14, 1, ''uint8'');\n' ...
 'bat_known = v_bat >= single(%s);\n' ...
 '%% EGR: running, the stall guard not holding it off, a workable battery\n' ...
 '%% (unknown counts as fine: production may not measure it)\n' ...
 'egr = running ~= 0 && egr_off == 0 && ...\n' ...
 '      (~bat_known || (v_bat >= single(%s) && v_bat <= single(%s)));\n' ...
 'd = abs(egr_duty);\n' ...
 'c(1) = uint8(egr && d > single(%s) && i_egr_f <= single(%s));\n' ...
 'c(2) = uint8(egr && egr_pos_ok ~= 0 && d < single(%s) && egr_pos > single(%s));\n' ...
 'c(3) = uint8(egr && egr_pos_ok ~= 0 && egr_duty >= single(%s) && egr_pos < single(%s));\n' ...
 '%% the metering valve: only where its current is measured\n' ...
 'c(4) = uint8(i_mu_valid ~= 0 && mu_duty * v_bat / single(%s) > single(%s) && i_mu < single(%s));\n' ...
 'c(5) = uint8(i_mu_valid ~= 0 && i_mu > single(%s));\n' ...
 'dev = abs(rail_set - rail_bar);\n' ...
 'c(6) = uint8(running ~= 0 && rail_ok ~= 0 && dev > single(%s) && dev > single(%s) * rail_set);\n' ...
 'c(7) = uint8(running ~= 0 && rpm > single(%s));\n' ...
 '%% stopped, yet oil pressure says turning / is implausible\n' ...
 'c(8) = uint8(ign_on ~= 0 && stopped ~= 0 && oil_ok ~= 0 && oil_kpa > single(%s));\n' ...
 'c(9) = uint8(ign_on ~= 0 && stopped ~= 0 && oil_ok ~= 0 && oil_kpa > single(%s) && oil_kpa <= single(%s));\n' ...
 'if bat_high_act ~= 0\n    bh = single(%s);\nelse\n    bh = single(%s);\nend\n' ...
 'c(10) = uint8(ign_on ~= 0 && bat_known && v_bat > bh);\n' ...
 '%% running only: cranking pulls any battery below 10 V\n' ...
 'if bat_low_act ~= 0\n    bl = single(%s);\nelse\n    bl = single(%s);\nend\n' ...
 'c(11) = uint8(running ~= 0 && bat_known && v_bat < bl);\n' ...
 '%% coolant: only from a good sensor (a faulted one reads its default)\n' ...
 'if clt_warn_act ~= 0\n    cw = single(%s);\nelse\n    cw = single(%s);\nend\n' ...
 'c(12) = uint8(ign_on ~= 0 && clt_ok ~= 0 && clt_c > cw);\n' ...
 'if clt_stop_act ~= 0\n    cs = single(%s);\nelse\n    cs = single(%s);\nend\n' ...
 'c(13) = uint8(ign_on ~= 0 && clt_ok ~= 0 && clt_c > cs);\n' ...
 'c(14) = uint8(ign_on ~= 0 && clt_low ~= 0);\n'], ...
 args, n(P.DG_BAT_MEASURED_V), n(P.DG_BAT_EGR_LO), n(P.DG_BAT_EGR_HI), ...
 n(P.DG_EGR_DRIVE), n(P.DG_EGR_OPEN_A), n(P.DG_EGR_COAST), n(P.DG_EGR_POS_PCT), ...
 n(P.DG_EGR_HARD), n(P.DG_EGR_POS_PCT), ...
 n(P.DG_MU_R_HI), n(P.DG_MU_EXPECT_A), n(P.DG_MU_OPEN_A), n(P.DG_MU_MAX_A), ...
 n(P.DG_RAIL_DEV_BAR), n(P.DG_RAIL_DEV_FRAC), n(P.DG_SPD_HIGH_RPM), ...
 n(P.DG_OIL_RUN_KPA), n(P.DG_OIL_STOP_KPA), n(P.DG_OIL_RUN_KPA), ...
 n(P.DG_BAT_HIGH_RET_V), n(P.DG_BAT_HIGH_V), n(P.DG_BAT_LOW_RET_V), n(P.DG_BAT_LOW_V), ...
 n(P.DG_CLT_WARN_RET_C), n(P.DG_CLT_WARN_C), n(P.DG_CLT_STOP_RET_C), n(P.DG_CLT_STOP_C));
types = containers.Map(ins(:, 1)', ins(:, 2)');
types('c') = U;
mfun(m, 'cond', src, types);
for i = 1:size(ins, 1)
    mb.l(m, sprintf('%s/1', ins{i, 1}), sprintf('cond/%d', i));
end
mb.l(m, 'cond/1', 'c/1');
set_param(m, 'Description', ['Engine-side diagnoses and coolant protection, 14 conditions. ' ...
    'Source of truth for firmware/gen/ecu_diag.']);
mb.finish(m);
end
