function mdl_ecu_crankrd(P)
%MDL_ECU_CRANKRD  What the rest of the firmware reads from the crank
%   decoder's state (firmware/core/crank.c crank_rpm, crank_angle,
%   crank_next_angle, crank_us_per_deg; decisions log 41):
%   - rpm over the last CRANK_WIN periods, the gap counted as its 18 deg
%     (0 until the window is full);
%   - the cycle angle, rev x 360 + tooth x 6, and the next edge's (18 deg
%     on from the last tooth before the gap, else 6);
%   - microseconds per degree at that speed (0 while it is 0).
%   The state is ecu_crank's packed pair (u32 a, u8 b).
m = 'ecu_crankrd';
mb.new(m);
U8 = 'uint8'; U32 = 'uint32'; S = 'single';
h = mb.in(m, 'a', U32); set_param(h, 'PortDimensions', '8');
h = mb.in(m, 'b', U8); set_param(h, 'PortDimensions', '33');
for o = {'rpm', 'angle', 'next_angle', 'us_per_deg'}, mb.out(m, o{1}, S); end
src = sprintf([ ...
 'function [rpm, angle, next_angle, us_per_deg] = rd(a, b)\n' ...
 '%%#codegen\n' ...
 'WIN = int32(%d); EDGES = uint8(%d);\n' ...
 'if b(7) < uint8(WIN)                    %% nper\n' ...
 '    rpm = single(0);\n' ...
 'else\n' ...
 '    us = uint32(0); deg = uint32(0);\n' ...
 '    for i = int32(1):WIN\n' ...
 '        us = us + a(2 + i); deg = deg + uint32(b(i));\n' ...
 '    end\n' ...
 '    rpm = single(deg) / single(us) * single(1e6) / single(6);\n' ...
 'end\n' ...
 'angle = single(b(14)) * single(360) + single(b(10)) * single(6);\n' ...
 'if b(10) == EDGES - uint8(1)\n' ...
 '    next_angle = angle + single(18);\n' ...
 'else\n' ...
 '    next_angle = angle + single(6);\n' ...
 'end\n' ...
 'if rpm > single(0)\n' ...
 '    us_per_deg = single(1e6) / (rpm * single(6));\n' ...
 'else\n' ...
 '    us_per_deg = single(0);\n' ...
 'end\n'], P.CRANK_WIN, P.CRANK_TEETH - 2);
mfun(m, 'rd', src, containers.Map({'a', 'b', 'rpm', 'angle', 'next_angle', 'us_per_deg'}, {U32, U8, S, S, S, S}));
mb.l(m, 'a/1', 'rd/1'); mb.l(m, 'b/1', 'rd/2');
o = {'rpm', 'angle', 'next_angle', 'us_per_deg'};
for i = 1:4, mb.l(m, sprintf('rd/%d', i), [o{i} '/1']); end
set_param(m, 'Description', 'Crank speed and angle from the decoder state. Source of truth for firmware/gen/ecu_crankrd.');
mb.finish(m);
end
