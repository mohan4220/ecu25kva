function mdl_ecu_sensaux(P)
%MDL_ECU_SENSAUX  Pin 79, charge-air temperature (firmware/core/sensors.c
%   sens_aux_step_1ms; decisions log 33, 34). The NTC inside the boost
%   sensor (Bosch 0 281 006 102): the coolant's front end and table, its
%   own debounced range fault, no end-of-line trim. A channel of its own
%   so the end-of-line record keeps its five-sensor format.
%
%   Each step: the 5 V reference (outside 4.5-5.5 V the nominal 5 V);
%   the input made ratiometric; above SENS_V_HI FMI 3, below the coolant's
%   low limit FMI 4; a change of fault state must hold SENS_FAULT_MS
%   ticks; while faulted the value is SENS_AUX_DEFAULT. The NTC reading
%   takes out the 260k divider (NTC_LOAD) and looks up Bosch's table in
%   ln(R). State in three Unit Delays, as in ecu_sensors.
m = 'ecu_sensaux';
mb.new(m);
S = 'single';
mb.in(m, 'v', S);
mb.in(m, 'v_5v', S);
mb.out(m, 'val', S);
mb.out(m, 'fmi', 'uint8');

n = @(x) mb.num(single(x));
src = sprintf([ ...
 'function [val, fmi, bad_n, fmi_n, val_n] = aux(v, v_5v, bad, fmi_p, val_p)\n' ...
 '%%#codegen\n' ...
 'NT = single(%s); NR = single(%s);\n' ...
 'v5 = v_5v;\n' ...
 'if ~(v5 >= single(4.5) && v5 <= single(5.5))\n' ...
 '    v5 = single(5);\n' ...
 'end\n' ...
 'bad_n = bad; fmi_n = fmi_p; val_n = val_p;\n' ...
 'vr = v * single(5) / v5;\n' ...
 'if ~(vr <= single(%s))\n' ...
 '    now = uint8(3);\n' ...
 'elseif vr < single(%s)\n' ...
 '    now = uint8(4);\n' ...
 'else\n' ...
 '    now = uint8(0);\n' ...
 'end\n' ...
 'if (now ~= 0) ~= (fmi_n ~= 0)\n' ...
 '    bad_n = bad_n + uint16(1);\n' ...
 '    if bad_n >= uint16(%d)\n' ...
 '        fmi_n = now;\n' ...
 '        bad_n = uint16(0);\n' ...
 '    end\n' ...
 'else\n' ...
 '    bad_n = uint16(0);\n' ...
 '    if now ~= 0\n' ...
 '        fmi_n = now;\n' ...
 '    end\n' ...
 'end\n' ...
 'if fmi_n ~= 0\n' ...
 '    val_n = single(%s);\n' ...
 'elseif now == 0\n' ...
 '    r = single(%s) * vr / (single(5) - vr);\n' ...
 '    if r < single(%s)\n' ...
 '        r = r * single(%s) / (single(%s) - r);\n' ...
 '    else\n' ...
 '        r = single(1e9);\n' ...
 '    end\n' ...
 '    if ~(r < NR(1))\n' ...
 '        val_n = NT(1);\n' ...
 '    elseif r <= NR(20)\n' ...
 '        val_n = NT(20);\n' ...
 '    else\n' ...
 '        k = int32(1);\n' ...
 '        while r <= NR(k + 1)\n' ...
 '            k = k + int32(1);\n' ...
 '        end\n' ...
 '        val_n = NT(k) + (NT(k + 1) - NT(k)) * (log(NR(k) / r) / log(NR(k) / NR(k + 1)));\n' ...
 '    end\n' ...
 'end\n' ...
 'val = val_n; fmi = fmi_n;\n'], ...
 n(P.ntc_t), n(P.ntc_r), n(P.SENS_V_HI), n(P.sens_v_lo(1)), P.SENS_FAULT_MS, ...
 n(P.SENS_AUX_DEFAULT), n(P.NTC_PULLUP), n(P.NTC_LOAD), n(P.NTC_LOAD), n(P.NTC_LOAD));
mfun(m, 'aux', src, containers.Map( ...
    {'v', 'v_5v', 'bad', 'fmi_p', 'val_p', 'val', 'fmi', 'bad_n', 'fmi_n', 'val_n'}, ...
    {S, S, 'uint16', 'uint8', S, S, 'uint8', 'uint16', 'uint8', S}));
mb.b(m, 'bad_z', 'simulink/Discrete/Unit Delay', 'InitialCondition', '0');
mb.b(m, 'fmi_z', 'simulink/Discrete/Unit Delay', 'InitialCondition', '0');
mb.b(m, 'val_z', 'simulink/Discrete/Unit Delay', 'InitialCondition', n(P.SENS_AUX_DEFAULT));
set_param([m '/bad_z'], 'SampleTime', '-1');
set_param([m '/fmi_z'], 'SampleTime', '-1');
set_param([m '/val_z'], 'SampleTime', '-1');
mb.l(m, 'v/1', 'aux/1'); mb.l(m, 'v_5v/1', 'aux/2');
mb.l(m, 'bad_z/1', 'aux/3'); mb.l(m, 'fmi_z/1', 'aux/4'); mb.l(m, 'val_z/1', 'aux/5');
mb.l(m, 'aux/3', 'bad_z/1'); mb.l(m, 'aux/4', 'fmi_z/1'); mb.l(m, 'aux/5', 'val_z/1');
mb.l(m, 'aux/1', 'val/1'); mb.l(m, 'aux/2', 'fmi/1');
set_param(m, 'Description', 'Charge-air temperature, pin 79. Source of truth for firmware/gen/ecu_sensaux.');
mb.finish(m);
end
