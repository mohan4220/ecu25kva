function mdl_ecu_lamps(P)
%MDL_ECU_LAMPS  DM1's lamps for the active faults (firmware/core/safety.c
%   fault_lamps; decisions log 35, 41). Red and Protect for a shutdown:
%   overspeed (190/0), crank position lost (636, any FMI), the injector
%   boost rail over its limit (520192/0), coolant too hot (110/0); amber
%   for every other active fault. The DSE4522 shuts the set down only on
%   Protect, so this decides which faults stop the engine.
%
%   The active-fault table comes in as its SPN and FMI columns
%   (FAULTS_MAX each) and its count; only the first n are read.
m = 'ecu_lamps';
mb.new(m);
U8 = 'uint8'; U32 = 'uint32';
h = mb.in(m, 'spn', U32); set_param(h, 'PortDimensions', num2str(P.FAULTS_MAX));
h = mb.in(m, 'fmi', U8); set_param(h, 'PortDimensions', num2str(P.FAULTS_MAX));
mb.in(m, 'n', U8);
mb.out(m, 'lamps', U8);
src = sprintf([ ...
 'function lamps = lamps_of(spn, fmi, n)\n' ...
 '%%#codegen\n' ...
 'lamps = uint8(0);\n' ...
 'last = min(int32(n), int32(%d));\n' ...
 'for i = int32(1):last\n' ...
 '    s = spn(i); f = fmi(i);\n' ...
 '    if (s == uint32(%d) && f == uint8(0)) || s == uint32(%d) ...\n' ...
 '            || (s == uint32(%d) && f == uint8(%d)) || (s == uint32(%d) && f == uint8(0))\n' ...
 '        lamps = bitor(lamps, uint8(%d));      %% red + Protect: the DSE shuts down\n' ...
 '    else\n' ...
 '        lamps = bitor(lamps, uint8(%d));      %% amber\n' ...
 '    end\n' ...
 'end\n'], ...
 P.FAULTS_MAX, P.SPN_SPEED, P.SPN_POS, P.SPN_BOOST_RAIL, P.FMI_HIGH_SEVERE, P.SPN_CLT, ...
 bitor(P.LAMP_RED, P.LAMP_PROTECT), P.LAMP_AMBER);
mfun(m, 'lamps_of', src, containers.Map({'spn', 'fmi', 'n', 'lamps'}, {U32, U8, U8, U8}));
mb.l(m, 'spn/1', 'lamps_of/1'); mb.l(m, 'fmi/1', 'lamps_of/2'); mb.l(m, 'n/1', 'lamps_of/3');
mb.l(m, 'lamps_of/1', 'lamps/1');
set_param(m, 'Description', 'DM1 lamps: which faults light Protect. Source of truth for firmware/gen/ecu_lamps.');
mb.finish(m);
end
