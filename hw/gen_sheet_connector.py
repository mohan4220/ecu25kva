#!/usr/bin/env python3
"""connector sheet: the 94-way ECU harness connector and what lands on it.

This sheet has no simulation block behind it because it is not a circuit.
It is the boundary, and its job is to be checkable against the machine:
every pin the ECU's terminal diagram shows, wired to the net the sheet
that owns that signal already named, and every other position left
visibly empty.

THE PINOUT IS BOSCH'S, since 8 November 2026. refs/bosch-pinout-md1cs162.md
was read off Bosch's terminal diagram for this ECU (0 462 YU4 15D,
"MD1CS162 KOEL CPCB4+ 3 cyl"); the owner confirmed it applies to our
engine and made it the master. It shows 46 pins and gives each one a
function. It replaces refs/ecu-pinout-extracted.md (KOEL's harness
diagram GP3.8703.C4) where the two disagree, and they disagree on power:

  KOEL: pin 21 a permanent battery feed, no ground shown.
  Bosch: no permanent feed. Pin 71 (ignition) wakes the ECU, pin 50
         closes the main relay, the relay feeds 04/06. 01/02 are the
         power ground. Pin 21 is the water-in-fuel switch.

So the power-ground gap this sheet recorded from 19 September is closed
by pins 01/02, and the trip loop, which had no pin, is gone (decisions
log sec.18).

THE PART NUMBER is off the physical housing (refs/field-evidence-
2026-09-18.md sec.2b): Bosch 1 928 405 192 / 194, CODE C, PA66-GF50.
Code C is mechanical keying: a differently-coded housing will not mate.
The owner decided on 22 September 2026 that the ECU carries THIS
connector on the board and plugs straight into the unmodified OEM loom,
so its board-side land pattern is load-bearing and still needed.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import json
import schlib
from schlib import Sheet, pin_xy

HW = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HW, "connector.kicad_sch")
ICPINS = json.load(open(os.path.join(HW, "lib", "ic_pins.json")))
CONN = "ecu25kva:CONN_ECU_94"
STUB = 24.0

# ECU pin -> the hierarchical net the owning sheet already named. Every
# left-hand number is a pin on Bosch's terminal diagram for this ECU
# (refs/bosch-pinout-md1cs162.md), the master pinout since 8 Nov 2026,
# and every right-hand name already exists on another sheet. Bosch's
# own pin names are in the comments.
NETS = {
    # -- power: the main relay's contact feeds 04/06, the board's only
    #    supply. 04 also feeds the electronics (power_input). --
    "4": "V_BAT_1R",            # V_V_BAT_1R
    "6": "V_BAT_2R",            # V_V_BAT_2R
    # -- analog sensors --
    "11": "EXC_BOOST_11", "41": "BOOST_P_IN", "79": "BOOST_T_IN",
    "34": "SGND_34", "33": "COOLANT_T_IN",
    "15": "EXC_EGR_15", "37": "EGR_POS_IN", "36": "SGND_36",
    "39": "EXC_OIL_39", "80": "OIL_P_IN",
    "32": "EXC_RAIL_32", "35": "RAIL_P_IN",
    "9": "SYNC_IN_09",          # I_A_SYNC, analog from the GCU
    # -- speed --
    "45": "EXC_CAM_45", "46": "CAM_FREQ_46", "44": "CAM_GND_44",
    "52": "CRANK_HI_52", "74": "CRANK_LO_74", "30": "SHIELD_30",
    # -- discrete in --
    "43": "SW_COOLANT_C", "23": "SW_DROOP_C",
    "20": "IN_AUDIO_ABORT_H", "24": "IN_OVERRIDE_SS_H",
    "71": "IN_IGNITION_H",      # I_S_T15: also wakes the board
    "21": "IN_WIF_H",           # I_S_WFLS, water in fuel
    "14": "SW_DIAG_C",          # I_S_DIA
    "25": "SW_STOP_C",          # I_S_STST, stop / emergency
    # -- outputs --
    "88": "MU_RETURN", "50": "RLY_MAIN_OUT", "69": "RLY_BUZZER_OUT",
    "59": "EGR_HIGH_59", "81": "EGR_LOW_81",
    # -- injectors --
    "3": "INJ_A_03", "5": "INJ_B_05",
    "73": "INJ_LS1_73", "7": "INJ_LS3_07", "29": "INJ_LS2_29",
    # -- CAN. Bosch: 87/86 is CAN 1, application line, 1000 kbit/s,
    #    flashing and UDS; 55/77 is CAN 2, PT line, 250 kbit/s, J1939 and
    #    OBD. The net names predate that and are kept (decisions log 18). --
    "55": "CAN1_H", "77": "CAN1_L", "87": "CAN2_H", "86": "CAN2_L",
}

# Grounds at the ECU end. 01/02 are Bosch's G_G_BAT1/2, the POWER ground
# (terminal 31), which closes the gap this sheet recorded until 8 Nov
# 2026. 08 is the rail-pressure sensor's DEDICATED return: unlike 34 and
# 36 -- shared returns, carried into difference amplifiers as SIGNALS --
# a dedicated return has nothing to reject and is simply ground here.
GROUNDED = {"1": "G_G_BAT1, power ground", "2": "G_G_BAT2, power ground",
            "8": "rail-pressure dedicated sensor return"}

def build():
    schlib.verify_pins()
    sh = Sheet("94-way ECU connector and harness mapping", paper="A2",
               comments=[
                   "Generated by hw/gen_sheet_connector.py -- do not hand-edit until it is retired",
                   "Pinout: Bosch terminal diagram 0 462 YU4 15D via refs/bosch-pinout-md1cs162.md (46 pins)",
                   "Power: pin 71 wakes, pin 50 closes the main relay, 04/06 feed the board, 01/02 are ground",
                   "Bosch 1 928 405 192 / 194 code C ON THE BOARD, no adapter (owner, 22 Sep) -- land pattern still needed",
               ],
               ref_base=schlib.REF_BASE["connector"])
    cx, cy = 297.0, 200.0
    sh.place(CONN, "J", cx, cy, "CONN_ECU_94", ref="J1001",
             fields={"Source": "refs/bosch-pinout-md1cs162.md (46 pins, "
                               "Bosch 0 462 YU4 15D); "
                               "refs/field-evidence-2026-09-18.md sec.2b "
                               "(part numbers, off the housing)",
                     "MPN": "Bosch 1 928 405 192 / 194, CODE C",
                     "Note": "Bosch 94-way ECU connector, EDC17 family, "
                             "PA66-GF50 housing. Code C is a MECHANICAL "
                             "coding variant -- a differently-coded "
                             "housing will not mate.",
                     "FootprintStatus": "not assigned: the board-side land "
                             "pattern needs the mating half's drawing, via "
                             "a Bosch distributor. No catalogue hit on "
                             "either number.",
                     "Shown": "46 of 94 pins on Bosch's terminal diagram"})

    geom = ICPINS["CONN_ECU_94"]
    wired = 0
    for n in range(1, 95):
        num = str(n)
        px, py = pin_xy(*geom[num], cx, cy, 0)
        left = px < cx
        ex = px - STUB if left else px + STUB
        if num in NETS:
            sh.wire(px, py, ex, py)
            sh.hlabel(NETS[num], ex, py, shape="passive",
                      rot=180 if left else 0)
            wired += 1
        elif num in GROUNDED:
            # Taken clear of the stub column before it drops. At 2.54 mm
            # pitch EVERY multiple of the pitch below a pin is another
            # pin's row: the first version dropped 7.62 mm and landed
            # exactly on pin 11's label anchor, which put the boost
            # sensor's 5 V excitation on GND in the netlist while the
            # page still plotted correctly. It then goes UP, clear of
            # the stub column, because dropping it landed the ground
            # symbol on top of pin 20's label instead.
            # Each grounded pin drops in its own column, so their symbols
            # do not stack: 08 at 30 mm as before, 01/02 further out.
            gx = ex - {"1": 42.0, "2": 36.0}.get(num, 30.0)
            sh.wire(px, py, ex, py)
            sh.wire(ex, py, gx, py)
            sh.wire(gx, py, gx, py - 34.0)
            sh.gnd(gx, py - 34.0)
            wired += 1

    sh.text("J1 -- 94-way ECU harness connector", cx - 36.0, cy - 70.0,
            size=2.0)
    sh.text(f"{wired} pins wired, {94 - wired} left deliberately empty",
            cx - 36.0, cy - 64.0, size=1.6)

    sh.text(
        "POWER, AS BOSCH WIRES IT.\n"
        "\n"
        "There is no permanent battery feed. The main relay's coil sits\n"
        "between Term. 30 and pin 50; its contact feeds pins 04 and 06\n"
        "through two 10 A fuses, and those are the board's only supply.\n"
        "Pin 71 (ignition) closes the relay in hardware through the wake\n"
        "FET on discrete_io, so the board can come up at all. The MCU\n"
        "then holds pin 50 through the after-run and releases it last.\n"
        "\n"
        "Pin 04 feeds the electronics (power_input's 5 A fuse, EMI filter,\n"
        "TVS, reverse FET, buck) AND the injector stage; pin 06 the EGR\n"
        "bridge. 01 and 02 are the power ground (G_G_BAT1/2): the 18 A\n"
        "injector return lands there.\n"
        "\n"
        "Pin 21 is NOT battery. It is the water-in-fuel switch, active\n"
        "high from the main-relay line, open with no water.",
        14.0, 130.0, size=1.6)

    sh.text(
        "PINS ADDED FROM THE BOSCH DIAGRAM\n"
        "\n"
        "  09  I_A_SYNC   analog synchronisation input from the GCU\n"
        "                 -> sensors_analog divider -> PTB0\n"
        "  14  I_S_DIA    diagnosis request, GCU contact to ground\n"
        "  21  I_S_WFLS   water in fuel, active high\n"
        "  25  I_S_STST   stop / emergency switch, contact to ground\n"
        "  01  G_G_BAT1,  02  G_G_BAT2   power ground\n"
        "\n"
        "CAN: Bosch's CAN 1 (application line, 1000 kbit/s, flashing\n"
        "and UDS) is 87/86, net CAN2_*; its CAN 2 (PT line, 250 kbit/s,\n"
        "J1939 and OBD) is 55/77, net CAN1_*. Names kept, mapping noted.\n"
        "\n"
        "WHY PINS 34 AND 36 ARE SIGNALS AND PIN 08 IS GROUND\n"
        "\n"
        "  34 and 36 are SHARED sensor returns -- 34 for boost pressure\n"
        "  and coolant temperature, 36 for EGR position and oil\n"
        "  pressure. A shared return carries both sensors' current, so\n"
        "  its own resistance is an offset on both readings, which is\n"
        "  why sensors_analog carries them into difference amplifiers\n"
        "  rather than to ground. 08 is rail pressure's DEDICATED\n"
        "  return: nothing to reject, so it is simply ground here.",
        400.0, 130.0, size=1.6)

    sh.text(
        "THE PART IS IDENTIFIED; THE LAND PATTERN IS NOT. "
        "refs/field-evidence-2026-09-18.md sec.2b closed U1 off a "
        "photograph of the housing angled to the light: BOSCH and the "
        "armature-in-circle logo moulded on the side body, "
        "1 928 405 194 under the BOSCH text, 1 928 405 192 on the lower\n"
        "body strip, CODE C beside it, >PA66-GF50< on the locking lever. "
        "Read off the physical part, which beats a catalogue match "
        "because it cannot be a mis-identification. CODE C IS "
        "LOAD-BEARING: Bosch supplies these housings mechanically coded\n"
        "so differently-coded plugs cannot mate, so any replacement or "
        "adapter must match it or it will not engage -- the kind of "
        "detail that is invisible until a part arrives and will not "
        "fit. The PIN LIST is Bosch's terminal diagram (8 Nov 2026). "
        "Still missing: the board-side footprint. A search for both "
        "numbers returned no catalogue hit, so the land\n"
        "pattern has to come through a Bosch distributor quoting them, "
        "or off the old ECU's header (brief Group 6). Nothing is "
        "assigned here, because a mating land pattern is not a thing to "
        "infer from a photograph.",
        14.0, 390.0, size=1.6)
    return sh


if __name__ == "__main__":
    print(build().write(OUT, force="--force" in sys.argv))
